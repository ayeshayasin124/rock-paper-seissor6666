"""### 5. Model Development: Train-Test Split and Decision Tree Regressor
We will now use `scikit-learn` to prepare our data, split it into 80% training and 20% testing sets, train a Decision Tree Regressor to predict `Calories` based on other nutritional facts, and evaluate its performance.
"""

from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeRegressor
from sklearn.metrics import mean_squared_error, r2_score
import pandas as pd

# Define features (X) and target (y)
# We'll use numerical nutritional features to predict Calories
feature_cols = [
    'Total Fat (g)', 'Trans Fat (g)', 'Saturated Fat (g)', 'Sodium (mg)',
    'Total Carbohydrates (g)', 'Cholesterol (mg)', 'Dietary Fibre (g)',
    'Sugars (g)', 'Protein (g)', 'Vitamin A (% DV)', 'Vitamin C (% DV)',
    'Calcium (% DV)', 'Iron (% DV)', 'Caffeine (mg)'
]

X = df[feature_cols]
y = df['Calories']

# Perform 80% training and 20% testing split
X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.20, random_state=42)

print(f"Training set shape: {X_train.shape}")
print(f"Testing set shape: {X_test.shape}")

# Initialize and train Decision Tree Regressor
dt_model = DecisionTreeRegressor(random_state=42, max_depth=5)
dt_model.fit(X_train, y_train)

# Make predictions
y_pred = dt_model.predict(X_test)

# Evaluate model performance
mse = mean_squared_error(y_test, y_pred)
rmse = np.sqrt(mse)
r2 = r2_score(y_test, y_pred)

print(f"\nModel Evaluation Metrics:")
print(f"Root Mean Squared Error (RMSE): {rmse:.2f} Calories")
print(f"R-squared (R2) Score: {r2:.4f}")

"""### 6. Feature Importance
Let's check which nutritional features contribute the most to predicting the calorie content of Starbucks beverages according to our Decision Tree.
"""

importances = dt_model.feature_importances_
feature_importance_df = pd.DataFrame({
    'Feature': feature_cols,
    'Importance': importances
}).sort_values(by='Importance', ascending=False)

plt.figure(figsize=(10, 6))
